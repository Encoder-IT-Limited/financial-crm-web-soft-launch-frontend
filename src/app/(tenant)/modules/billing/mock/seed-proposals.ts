function line(description: string, quantity: number, unitPrice: number, taxRate: number): InvoiceLine {
  return {
    id: `ln-${description.slice(0, 4).toLowerCase()}-${quantity}-${unitPrice}`,
    description,
    quantity,
    unitPrice,
    taxRate,
    total: Math.round(quantity * unitPrice * 100) / 100,
  };
}


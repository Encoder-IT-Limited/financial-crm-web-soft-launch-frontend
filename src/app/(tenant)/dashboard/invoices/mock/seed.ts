function line(description: string, quantity: number, unitPrice: number, taxRate: number): InvoiceLine {
  return {
    id: `ln-${description.slice(0, 4).toLowerCase()}-${quantity}-${unitPrice}`,
    description,
    quantity,
    unitPrice,
    taxRate,
    total: Math.round(quantity * unitPrice * 100) / 100,
  };
}

/** Same as line(), but linked to a product/warehouse — makes the line
 * eligible for Delivery/Fulfillment (Phase I). productId/warehouseId
 * match product-lookup-seed.ts's demo catalog. */
function productLine(
  description: string,
  quantity: number,
  unitPrice: number,
  taxRate: number,
  productId: string,
  warehouseId: string
): InvoiceLine {
  return { ...line(description, quantity, unitPrice, taxRate), productId, warehouseId };
}

